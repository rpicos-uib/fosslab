"""Start the interactive tools on a view, set up for the workspace and the IHP PDK."""

from __future__ import annotations

import os
import shlex
import subprocess
from pathlib import Path

from . import config
from .workspace import View, Workspace


def _tcl_brace(s: str) -> str:
    return "{" + str(s) + "}"


def xschem_setup(ws: Workspace) -> tuple[Path, dict[str, str]]:
    """Write <workspace>/.fosslab/xschemrc and return it with the env xschem needs."""

    ws.setup_dir.mkdir(parents=True, exist_ok=True)
    rc = ws.setup_dir / "xschemrc"
    libs = [lib for lib in ws.libraries(include_pdk=False)]
    lib_path = ":".join(str(p) for p in ws.xschem_library_path())
    lines = [
        "# Generated by FOSSLab at every launch: do not edit.",
        "# Put your own settings in xschemrc.user next to this file.",
        f"set env(XSCHEM_USER_LIBRARY_PATH) {_tcl_brace(lib_path)}",
        f"source {_tcl_brace(config.IHP_XSCHEMRC)}",
        "set fosslab_libs [list " + " ".join(
            "[list " + _tcl_brace(lib.name) + " " + _tcl_brace(lib.path) + "]" for lib in libs) + "]",
        f"set fosslab_runroot {_tcl_brace(ws.run_root)}",
        f"set netlist_dir {_tcl_brace(ws.run_root / 'sim')}",
        "set local_netlist_dir 0",
        "# the IHP PDK's symbols contain Tcl: do not ask at every schematic",
        "set xschem_execute_scripts yes",
        f"lappend tcl_files {_tcl_brace(config.INTEGRATIONS / 'xschem_fosslab.tcl')}",
        f"if {{[file exists {_tcl_brace(ws.setup_dir / 'xschemrc.user')}]}} "
        f"{{ source {_tcl_brace(ws.setup_dir / 'xschemrc.user')} }}",
    ]
    rc.write_text("\n".join(lines) + "\n")
    env = {"XSCHEM_USER_LIBRARY_PATH": lib_path, **ws_env(ws)}
    return rc, env


def ws_env(ws: Workspace) -> dict[str, str]:
    """Tell programs we start (and the fosslab commands their menus run)
    which workspace they belong to."""

    return {"FOSSLAB_WORKSPACE": str(ws.root), "FOSSLAB_RUN_ROOT": str(ws.run_root),
            "FOSSLAB_FROM_TOOL": "1"}


def ensure_user_xschemrc(ws: Workspace) -> None:
    """Make a plain ``xschem`` typed in a terminal behave like the one FOSSLab
    starts: ~/.xschem/xschemrc sources the generated file. A file the user
    wrote is never touched; xschem's own empty template is replaced."""

    user_rc = Path.home() / ".xschem" / "xschemrc"
    generated = ws.setup_dir / "xschemrc"
    line = f"source {_tcl_brace(generated)}  ;# added by FOSSLab\n"
    if user_rc.exists():
        text = user_rc.read_text(errors="replace")
        if "added by FOSSLab" in text:
            return
        if not text.startswith("#### xschemrc system configuration file"):
            return  # the user's own file
    user_rc.parent.mkdir(parents=True, exist_ok=True)
    user_rc.write_text(line)


def _env(extra: dict[str, str] | None = None) -> dict[str, str]:
    env = dict(os.environ)
    if extra:
        env.update(extra)
    return env


def spawn(argv: list[str], cwd: Path | None = None, env: dict[str, str] | None = None,
          log: Path | None = None) -> subprocess.Popen:
    """Start a GUI program, detached from us: closing the manager leaves it open."""

    out = open(log, "ab") if log else subprocess.DEVNULL
    if os.environ.get("FOSSLAB_DEBUG"):
        print("fosslab: launching", shlex.join(argv), "in", cwd)
    return subprocess.Popen(argv, cwd=str(cwd) if cwd else None, env=_env(env),
                            stdout=out, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL,
                            start_new_session=True)


def open_xschem(ws: Workspace, path: Path) -> subprocess.Popen:
    rc, env = xschem_setup(ws)
    return spawn(["xschem", "--rcfile", str(rc), str(path)], cwd=path.parent, env=env,
                 log=ws.setup_dir / "xschem.log")


def open_klayout(ws: Workspace, path: Path, cell: str | None = None,
                 rdb: Path | None = None, l2n: Path | None = None) -> subprocess.Popen:
    argv = ["klayout", "-e", "-n", config.KLAYOUT_TECH, str(path)]
    if rdb is not None:
        argv += ["-m", str(rdb)]
    if l2n is not None:
        argv += ["-mn", str(l2n)]
    if cell:
        argv += ["-rd", f"cell={cell}", "-rr", str(config.INTEGRATIONS / "klayout_select_cell.py")]
    env = ws_env(ws)
    ws.setup_dir.mkdir(parents=True, exist_ok=True)
    return spawn(argv, cwd=path.parent, env=env, log=ws.setup_dir / "klayout.log")


def open_magic(ws: Workspace, path: Path, cell: str | None = None) -> subprocess.Popen:
    ws.setup_dir.mkdir(parents=True, exist_ok=True)
    script = ws.setup_dir / "magic_open.tcl"
    if path.suffix == ".gds":
        script.write_text(f"gds read {_tcl_brace(path)}\nload {cell or path.stem}\nselect top cell\nexpand\n")
    else:
        script.write_text(f"cd {_tcl_brace(path.parent)}\nload {path.stem}\n")
    return spawn(["magic", "-d", "XR", "-rcfile", str(config.IHP_MAGICRC), str(script)],
                 cwd=path.parent, env=ws_env(ws), log=ws.setup_dir / "magic.log")


def open_editor(path: Path) -> subprocess.Popen:
    return spawn(shlex.split(config.editor()) + [str(path)], cwd=path.parent)


def open_terminal(cwd: Path) -> subprocess.Popen:
    return spawn(["xterm", "-title", f"FOSSLab: {cwd}", "-fa", "Monospace", "-fs", "11"], cwd=cwd)


def open_view(ws: Workspace, view: View, tool: str | None = None) -> subprocess.Popen:
    """Open a view in its default tool (or ``tool``: xschem, klayout, magic, editor)."""

    kind = view.kind
    path = view.path
    if tool is None:
        tool = {"schematic": "xschem", "symbol": "xschem", "layout": "klayout",
                "magic": "magic"}.get(kind, "editor")
    if tool == "xschem":
        return open_xschem(ws, path)
    if tool == "klayout":
        return open_klayout(ws, path, cell=view.cell_in_file)
    if tool == "magic":
        return open_magic(ws, path, cell=view.cell_in_file)
    return open_editor(path)


def open_waveforms(raw: Path) -> subprocess.Popen:
    """Look at a .raw file outside xschem (xschem's own graphs are the usual way)."""

    return spawn(["gaw", str(raw)], cwd=raw.parent)
